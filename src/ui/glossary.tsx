const TERMS = Object.keys(GLOSSARY).sort((a, b) => b.length - a.length);
const RE = new RegExp(`(${TERMS.join('|')})`, 'g');

function Term({ word }: { word: string }) {
  const [open, setOpen] = useState(false);
  return (
    <span class={`term ${open ? 'open' : ''}`} data-gloss={GLOSSARY[word]} onClick={(e) => (e.stopPropagation(), setOpen(!open))}>
      {word}
    </span>
  );
}

/** 把文字中的詞彙加上註解 */
export function Gloss({ text }: { text: string }) {
  const parts = text.split(RE);
  return (
    <>
      {parts.map((p, i) => (GLOSSARY[p] && i % 2 === 1 ? <Term key={i} word={p} /> : p))}
    </>
  );
}
